def family_for(phase: str, name: str) -> str:
    if phase == "off2on" and name in OFF2ON_NAMES:
        return "offline-to-online"
    matches = [family for family, names in FAMILIES.items() if name in names]
    if len(matches) != 1:
        raise ValueError(f"Classify {phase}/{name} into exactly one family: {matches}")
    return matches[0]


def expand_braces(path: str) -> list[str]:
    """Expand the grouped module spellings used by REFERENCES.md."""
    match = re.search(r"\{([^{}]+)\}", path)
    if match is None:
        return [path]
    return [
        expanded
        for choice in match[1].split(",")
        for expanded in expand_braces(path[:match.start()] + choice + path[match.end():])
    ]


def read_references() -> dict[str, tuple[str, str]]:
    references = {}
    for line in (ROOT / "docs/REFERENCES.md").read_text(encoding="utf-8").splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) != 4 or "`" not in cells[1]:
            continue
        key, paths, paper, _ = cells
        for path in re.findall(r"`([^`]+)`", paths):
            for expanded in expand_braces(path):
                if not expanded.endswith(".py"):
                    continue
                if not expanded.startswith("algorithms/"):
                    expanded = "algorithms/" + expanded
                module = "rl_garden." + expanded[:-3].replace("/", ".")
                # Repeated module rows (e.g. offline/off2on FloQ) cite the same paper.
                references.setdefault(module, (key, paper))
    return references


def rst_paper(text: str) -> str:
    return re.sub(r"\[([^]]+)\]\(([^)]+)\)", r"`\1 <\2>`_", text)


def list_table(title: str, headers: list[str], rows: list[list[str]]) -> str:
    lines = [title, "=" * len(title), "", ".. Generated by tools/docs/gen_tables.py; do not edit.", "",
             ".. list-table::", "   :header-rows: 1", ""]
    for row in [headers, *rows]:
        lines.append("   * - " + row[0])
        lines.extend("     - " + cell for cell in row[1:])
    return "\n".join(lines) + "\n"


def generate(destination: Path) -> None:
    references = read_references()
    rows = []
    missing_classes, missing_references = [], []
    for phase in ("online", "offline", "off2on"):
        registry = importlib.import_module(f"rl_garden.training.{phase}.registry").registry
        registry.discover()
        for name, entry in sorted(registry.entries().items()):
            cls = entry.algorithm_cls() if entry.algorithm_cls else None
            module = cls.__module__ if cls else NO_THUNK_MODULES.get((phase, name))
            reference = references.get(module)
            if cls is None:
                missing_classes.append(f"{phase}/{name}")
            if reference is None:
                missing_references.append(f"{phase}/{name} ({module})")
            rows.append([
                f"``{name}``", phase,
                f"``{module}.{cls.__name__}``" if cls else "—",
                f":doc:`/algorithms/{family_for(phase, name)}`",
                rst_paper(reference[1]) if reference else "—",
            ])
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "algorithms.rst").write_text(
        list_table("Algorithm registry", ["Registry name", "Phase", "Class", "Family", "Reference"], rows),
        encoding="utf-8",
    )

    from rl_garden.envs import backend_registry

    backend_registry.discover_env_backends()
    with (ROOT / "pyproject.toml").open("rb") as stream:
        extras = tomllib.load(stream)["project"]["optional-dependencies"]
    rows = []
    # The backend registry currently has no public enumeration function.
    for name, cls in sorted(backend_registry._REGISTRY.items()):
        extra = "d4rl-legacy" if name == "d4rl_legacy" else name
        rows.append([
            f"``{name}``", f"``{cls.__module__}.{cls.__name__}``",
            f"``{extra}``" if extra in extras else "—",
            f":doc:`/{BACKEND_PAGES[name]}`",
        ])
    (destination / "backends.rst").write_text(
        list_table("Environment backend registry", ["Name", "Class", "Extra", "Page"], rows)
        + "\nAn em dash means pyproject.toml declares no dedicated extra with that backend name.\n"
        + "Consult the linked page for core dependencies or separate simulator installation.\n",
        encoding="utf-8",
    )
    print("No class thunk: " + (", ".join(missing_classes) or "none"))
    print("No REFERENCES module row: " + (", ".join(missing_references) or "none"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed tables differ.")
    args = parser.parse_args(argv)
    if not args.check:
        generate(DESTINATION)
        print("Wrote algorithms.rst and backends.rst")
        return 0
    with tempfile.TemporaryDirectory(prefix="rlgarden-docs-") as directory:
        generated = Path(directory)
        generate(generated)
        changed = [path.name for path in sorted(generated.iterdir())
                   if not (DESTINATION / path.name).exists()
                   or path.read_bytes() != (DESTINATION / path.name).read_bytes()]
    if changed:
        print("Stale tables: " + ", ".join(changed) + "; run python tools/docs/gen_tables.py")
        return 1
    print("Generated tables are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
